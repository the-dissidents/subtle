describe('ASS color conversion', () => {
    it('parses &HAABBGGRR with inverted ASS alpha (00 = opaque, FF = transparent)', () => {
        const opaqueWhite = fromASSColor('&H00FFFFFF');
        expect(opaqueWhite).not.toBeNull();
        expect(opaqueWhite!.coords).toEqual([1, 1, 1]);
        expect(opaqueWhite!.alpha).toBeCloseTo(1, 5);

        const transparentBlack = fromASSColor('&HFF000000');
        expect(transparentBlack).not.toBeNull();
        expect(transparentBlack!.coords).toEqual([0, 0, 0]);
        expect(transparentBlack!.alpha).toBeCloseTo(0, 5);

        const semiShadow = fromASSColor('&H80000000');
        expect(semiShadow).not.toBeNull();
        expect(semiShadow!.coords).toEqual([0, 0, 0]);
        expect(semiShadow!.alpha).toBeCloseTo(1 - 0x80 / 255, 5);

        // &H0099F0B3 => AA=00 (opaque), BB=99, GG=F0, RR=B3
        const clipGreen = fromASSColor('&H0099F0B3');
        expect(clipGreen).not.toBeNull();
        expect(clipGreen!.coords[0]).toBeCloseTo(0xB3 / 255, 5);
        expect(clipGreen!.coords[1]).toBeCloseTo(0xF0 / 255, 5);
        expect(clipGreen!.coords[2]).toBeCloseTo(0x99 / 255, 5);
        expect(clipGreen!.alpha).toBeCloseTo(1, 5);
    });

    it('accepts 6-digit &HBBGGRR, trailing &, and surrounding whitespace', () => {
        const c1 = fromASSColor('  &H99F0B3& ');
        expect(c1).not.toBeNull();
        expect(c1!.coords[0]).toBeCloseTo(0xB3 / 255, 5);
        expect(c1!.coords[1]).toBeCloseTo(0xF0 / 255, 5);
        expect(c1!.coords[2]).toBeCloseTo(0x99 / 255, 5);
        expect(c1!.alpha).toBe(1);

        expect(fromASSColor('&H00FFFFFF&')?.alpha).toBe(1);
        expect(fromASSColor('not-a-color')).toBeNull();
    });

    it('round-trips colors cleanly without fractional hex digits', () => {
        for (const hex of ['&H00FFFFFF', '&H00CCCCCC', '&H0099F0B3', '&H00A3D9B5', '&H00DDEEFF', '&H80000000']) {
            const parsed = fromASSColor(hex)!;
            expect(toASSColor(parsed)).toBe(hex);
        }
    });
});

describe('ASSParser style matching', () => {
    it('matches all styles and colors in bilingual ASS files', () => {
        const { subs, messages } = new ASSParser(BILINGUAL_SAMPLE).decode();

        expect(messages).toEqual([]);
        expect(subs.metadata.width).toBe(1920);
        expect(subs.metadata.height).toBe(1080);
        expect(subs.styles.map((s) => s.name)).toEqual([
            'ZH_HOST',
            'EN_HOST',
            'ZH_CLIP',
            'EN_CLIP',
            'ZH_NOTE',
        ]);

        const byName = new Map(subs.styles.map((s) => [s.name, s]));

        const zhHost = byName.get('ZH_HOST')!;
        expect(zhHost.font).toBe('PingFang SC');
        expect(zhHost.size).toBe(60);
        expect(zhHost.styles.bold).toBe(true);
        expect(toASSColor(zhHost.color)).toBe('&H00FFFFFF');
        expect(toASSColor(zhHost.outlineColor)).toBe('&H00000000');
        expect(toASSColor(zhHost.shadowColor)).toBe('&H80000000');
        expect(zhHost.margin).toEqual({ top: 105, bottom: 105, left: 160, right: 160 });
        expect(zhHost.alignment).toBe(AlignMode.BottomCenter);

        const enHost = byName.get('EN_HOST')!;
        expect(enHost.font).toBe('Arial');
        expect(enHost.size).toBe(38);
        expect(enHost.styles.bold).toBe(false);
        expect(toASSColor(enHost.color)).toBe('&H00CCCCCC');
        expect(toASSColor(enHost.shadowColor)).toBe('&H80000000');

        const zhClip = byName.get('ZH_CLIP')!;
        expect(toASSColor(zhClip.color)).toBe('&H0099F0B3');

        const enClip = byName.get('EN_CLIP')!;
        expect(toASSColor(enClip.color)).toBe('&H00A3D9B5');

        const zhNote = byName.get('ZH_NOTE')!;
        expect(toASSColor(zhNote.color)).toBe('&H00DDEEFF');
        expect(zhNote.alignment).toBe(AlignMode.TopCenter);

        // Ensure all 5 dialogue entries bind directly to defined styles (no extra undefined styles created)
        expect(subs.entries).toHaveLength(5);
        expect(subs.entries[0].texts.has(enHost)).toBe(true);
        expect(subs.entries[1].texts.has(zhHost)).toBe(true);
        expect(subs.entries[2].texts.has(enClip)).toBe(true);
        expect(subs.entries[3].texts.has(zhClip)).toBe(true);
        expect(subs.entries[4].texts.has(zhNote)).toBe(true);
    });

    it('handles single-char comments, Format/Style text inside comments, spaces, American spelling, and missing trailing newline', () => {
        const tricky = `[Script Info]
Title: FirstLineTitle
PlayResX: 1280
PlayResY: 720

[V4+ Styles]
;
; Format: Fake, Should, Be, Ignored
; Style: FakeStyle,Arial,10,&H00000000
Format: Name, Fontname, Fontsize, PrimaryColor, OutlineColor, BackColor, Bold, Alignment
Style:  Main , Arial , 42 , &H00112233 , &H00445566 , &H80000000 , -1 , 2

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:01.00,0:00:02.00, Main ,,0,0,0,,Hello world`;

        const { subs, messages } = new ASSParser(tricky).decode();
        expect(messages).toEqual([]);
        expect(subs.metadata.title).toBe('FirstLineTitle');
        expect(subs.metadata.width).toBe(1280);
        expect(subs.metadata.height).toBe(720);
        expect(subs.styles).toHaveLength(1);

        const main = subs.styles[0];
        expect(main.name).toBe('Main');
        expect(main.font).toBe('Arial');
        expect(main.size).toBe(42);
        expect(toASSColor(main.color)).toBe('&H00112233');
        expect(toASSColor(main.outlineColor)).toBe('&H00445566');
        expect(toASSColor(main.shadowColor)).toBe('&H80000000');
        expect(subs.entries).toHaveLength(1);
        expect(subs.entries[0].texts.has(main)).toBe(true);
    });
});
